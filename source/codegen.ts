import { IComponentDef, IPropDef, IWorldDef } from "./schema";

function propDefaultExprJs(prop: IPropDef): string {
    if (prop.complex === "array") return "[]";
    if (prop.complex === "set") return "new Set()";
    if (prop.complex === "map") return "new Map()";

    const raw = (prop.defaultValue ?? "").trim();

    if (prop.kind === "cocos") {
        return "null";
    }
    if (prop.kind === "component") {
        return `C[${JSON.stringify(prop.type)}]()`;
    }
    if (prop.kind === "enum") {
        if (raw === "") return "0";
        const num = Number(raw);
        return Number.isFinite(num) ? String(num) : JSON.stringify(raw);
    }

    switch (prop.type) {
        case "float": {
            const n = raw === "" ? 0 : Number(raw);
            return Number.isFinite(n) ? String(n) : "0";
        }
        case "int": {
            const n = raw === "" ? 0 : Math.trunc(Number(raw));
            return Number.isFinite(n) ? String(n) : "0";
        }
        case "string":
            return JSON.stringify(raw);
        case "boolean":
            return raw.toLowerCase() === "true" || raw === "1" ? "true" : "false";
        case "object":
            return "{}";
        case "Int32Array": {
            const len = raw === "" ? 0 : Math.max(0, Math.trunc(Number(raw)));
            return `new Int32Array(${Number.isFinite(len) ? len : 0})`;
        }
        case "Uint32Array": {
            const len = raw === "" ? 0 : Math.max(0, Math.trunc(Number(raw)));
            return `new Uint32Array(${Number.isFinite(len) ? len : 0})`;
        }
        default:
            return "undefined";
    }
}

function propTypeDts(prop: IPropDef): string {
    let base: string;
    if (prop.kind === "component") {
        base = `I${prop.type}`;
    } else if (prop.kind === "cocos") {
        if (prop.tsType && prop.tsType.trim()) {
            base = prop.tsType.trim();
        } else {
            const clean = prop.type.startsWith("cc.") ? prop.type.slice(3) : prop.type;
            base = `import("cc").${clean}`;
        }
    } else if (prop.kind === "enum") {
        if (prop.tsType && prop.tsType.trim()) {
            base = prop.tsType.trim();
        } else {
            const clean = prop.type.startsWith("cc.") ? prop.type.slice(3) : prop.type;
            base = `import("cc").${clean}`;
        }
    } else {
        switch (prop.type) {
            case "float":
            case "int":
                base = "number";
                break;
            case "string":
                base = "string";
                break;
            case "boolean":
                base = "boolean";
                break;
            case "object":
                base = "Record<string, any>";
                break;
            case "Int32Array":
                base = "Int32Array";
                break;
            case "Uint32Array":
                base = "Uint32Array";
                break;
            default:
                base = "any";
                break;
        }
    }

    switch (prop.complex) {
        case "array":
            return `Array<${base}>`;
        case "set":
            return `Set<${base}>`;
        case "map":
            return `Map<pFlex.TKey, ${base}>`;
        case "single":
        default:
            return prop.kind === "cocos" ? `${base} | null` : base;
    }
}

export function generateComponentsJs(components: IComponentDef[]): string {
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
        "(function (root) {",
        '    "use strict";',
        "    root.pTS = root.pTS || {};",
        "    var schema = (root.pTS.__ecs_schema__ = root.pTS.__ecs_schema__ || {",
        "        components: Object.create(null),",
        "        worlds: Object.create(null),",
        "    });",
        "    var C = (schema.components = Object.create(null));",
        "",
    ];

    for (const comp of components) {
        const parents = Array.isArray(comp.extends)
            ? comp.extends.map((e) => String(e ?? "").trim()).filter(Boolean)
            : [];

        if (parents.length === 0) {
            if (comp.props.length === 0) {
                lines.push(`    C[${JSON.stringify(comp.name)}] = function () { return {}; };`);
            } else {
                lines.push(`    C[${JSON.stringify(comp.name)}] = function () {`);
                lines.push("        return {");
                for (const prop of comp.props) {
                    lines.push(`            ${prop.name}: ${propDefaultExprJs(prop)},`);
                }
                lines.push("        };");
                lines.push("    };");
            }
        } else {
            const parentCalls = parents.map((p) => `C[${JSON.stringify(p)}]()`).join(", ");
            if (comp.props.length === 0) {
                lines.push(`    C[${JSON.stringify(comp.name)}] = function () { return Object.assign({}, ${parentCalls}); };`);
            } else {
                lines.push(`    C[${JSON.stringify(comp.name)}] = function () {`);
                lines.push(`        return Object.assign({}, ${parentCalls}, {`);
                for (const prop of comp.props) {
                    lines.push(`            ${prop.name}: ${propDefaultExprJs(prop)},`);
                }
                lines.push("        });");
                lines.push("    };");
            }
        }
    }

    lines.push("");
    lines.push('    if (typeof schema._sync === "function") {');
    lines.push("        schema._sync();");
    lines.push("    }");
    lines.push('})(typeof globalThis !== "undefined" ? globalThis : (typeof window !== "undefined" ? window : (typeof self !== "undefined" ? self : this)));');
    lines.push("");
    return lines.join("\n");
}

export function generateComponentsDts(components: IComponentDef[]): string {
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
        "declare namespace pTS {",
        "    export namespace ecs_types {",
    ];

    for (const comp of components) {
        const parents = Array.isArray(comp.extends)
            ? comp.extends.map((e) => String(e ?? "").trim()).filter(Boolean)
            : [];
        const extendsClause = parents.length > 0 ? ` extends ${parents.map((p) => `I${p}`).join(", ")}` : "";
        lines.push(`        export interface I${comp.name}${extendsClause} {`);
        for (const prop of comp.props) {
            lines.push(`            ${prop.name}: ${propTypeDts(prop)};`);
        }
        lines.push("        }");
        lines.push("");
    }

    lines.push("        export interface IComponentMap {");
    for (const comp of components) {
        if (comp.is_component === false) continue;
        lines.push(`            ${comp.name}: I${comp.name};`);
    }
    lines.push("        }");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    return lines.join("\n");
}

export function generateWorldsJs(worlds: IWorldDef[]): string {
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
        "(function (root) {",
        '    "use strict";',
        "    root.pTS = root.pTS || {};",
        "    var schema = (root.pTS.__ecs_schema__ = root.pTS.__ecs_schema__ || {",
        "        components: Object.create(null),",
        "        worlds: Object.create(null),",
        "    });",
        "    var W = (schema.worlds = Object.create(null));",
        "",
    ];

    for (const w of worlds) {
        const maxExpr = w.max_entities === "Infinity" ? "Infinity" : String(Math.max(1, Math.floor(Number(w.max_entities))));
        const mode = w.event_mode === "manual" ? "manual" : "primitive";
        const evs = mode === "manual" ? (Array.isArray(w.events) ? w.events : []) : [];
        lines.push(`    W[${JSON.stringify(w.name)}] = {`);
        lines.push(`        name: ${JSON.stringify(w.name)},`);
        lines.push(`        components: ${JSON.stringify(w.components)},`);
        lines.push(`        max_entities: ${maxExpr},`);
        lines.push(`        auto_boost: ${w.auto_boost ? "true" : "false"},`);
        lines.push(`        event_mode: ${JSON.stringify(mode)},`);
        lines.push(`        events: ${JSON.stringify(evs)},`);
        lines.push("    };");
    }

    lines.push("");
    lines.push('    if (typeof schema._sync === "function") {');
    lines.push("        schema._sync();");
    lines.push("    }");
    lines.push('})(typeof globalThis !== "undefined" ? globalThis : (typeof window !== "undefined" ? window : (typeof self !== "undefined" ? self : this)));');
    lines.push("");
    return lines.join("\n");
}

export function generateWorldsDts(worlds: IWorldDef[]): string {
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
        "declare namespace pTS {",
        "    export namespace ecs_types {",
        "        export interface IWorldComponentMaps {",
    ];

    for (const w of worlds) {
        const key = JSON.stringify(w.name);
        if (w.components.length === 0) {
            lines.push(`            ${key}: Record<string, never>;`);
        } else {
            const union = w.components.map((c) => JSON.stringify(c)).join(" | ");
            lines.push(`            ${key}: Pick<IComponentMap, ${union}>;`);
        }
    }

    lines.push("        }");
    lines.push("");
    lines.push("        export interface IWorldEventMaps {");

    for (const w of worlds) {
        const key = JSON.stringify(w.name);
        const mode = w.event_mode === "manual" ? "manual" : "primitive";
        const evs = Array.isArray(w.events) ? w.events.map((e) => e.trim()).filter(Boolean) : [];
        if (mode === "manual" && evs.length > 0) {
            const union = evs.map((e) => JSON.stringify(e)).join(" | ");
            lines.push(`            ${key}: ${union};`);
        } else if (mode === "manual") {
            lines.push(`            ${key}: never;`);
        } else {
            lines.push(`            ${key}: string | symbol;`);
        }
    }

    lines.push("        }");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    return lines.join("\n");
}
