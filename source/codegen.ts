interface IParsedImport {
    mod: string;
    rootSym: string;
    expr: string;
}

function parseTsImport(tsType?: string, fallbackType?: string): IParsedImport | null {
    const raw = (tsType || "").trim();
    const m = /^import\((["'])(.+?)\1\)\.(.+)$/.exec(raw);
    if (m) {
        const mod = m[2];
        const expr = m[3].trim();
        const rootSym = expr.split(".")[0];
        if (mod && rootSym && expr) {
            return { mod, rootSym, expr };
        }
    }
    const fb = (fallbackType || "").trim();
    if (fb.startsWith("cc.")) {
        const expr = fb.slice(3);
        const rootSym = expr.split(".")[0];
        if (rootSym) return { mod: "cc", rootSym, expr };
    }
    return null;
}

function topoSortComponents(components: IComponentDef[]): IComponentDef[] {
    const byName = new Map<string, IComponentDef>();
    for (const c of components) byName.set(c.name, c);

    const visited = new Set<string>();
    const visiting = new Set<string>();
    const ordered: IComponentDef[] = [];

    const visit = (c: IComponentDef) => {
        if (visited.has(c.name) || visiting.has(c.name)) return;
        visiting.add(c.name);
        for (const ext of c.extends || []) {
            const parent = byName.get((ext || "").trim());
            if (parent) visit(parent);
        }
        for (const p of c.props) {
            if (p.kind === "component") {
                const dep = byName.get(p.type);
                if (dep) visit(dep);
            }
        }
        visiting.delete(c.name);
        visited.add(c.name);
        ordered.push(c);
    };

    for (const c of components) visit(c);
    return ordered;
}

function collectPropsRecursive(
    compName: string,
    byName: Map<string, IComponentDef>,
    seen: Set<string>,
    out: IPropDef[],
    takenPropNames: Set<string>,
): void {
    if (seen.has(compName)) return;
    seen.add(compName);
    const comp = byName.get(compName);
    if (!comp) return;
    for (const ext of comp.extends || []) {
        collectPropsRecursive((ext || "").trim(), byName, seen, out, takenPropNames);
    }
    for (const p of comp.props) {
        if (!takenPropNames.has(p.name)) {
            takenPropNames.add(p.name);
            out.push(p);
        }
    }
}

export function generateDtoTs(components: IComponentDef[], rawSettings?: Partial<IEcsSettings> | null): string {
    const settings = normalizeEcsSettings(rawSettings);
    const baseClassName = buildDtoClassName("Base", settings);

    if (!settings.auto_generate_dto) {
        const stubLines: string[] = [
            "// Auto-generated by pts-ecs (DTO auto-generation is disabled in Settings).",
            "// Enable \"Auto-Generate DTOs\" in the pTS-ECS Settings tab to generate @ccclass DTOs.",
            'import { _decorator } from "cc";',
            "",
            "const { ccclass } = _decorator;",
            "",
            `@ccclass(${JSON.stringify(baseClassName)})`,
            `export class ${baseClassName} {`,
            '    public readonly __comp_name__: string = "";',
            "    public to_plain(): Record<string, any> {",
            "        return {};",
            "    }",
            "}",
            "",
            ...(baseClassName !== "ECS_DTO_Base" ? [`export { ${baseClassName} as ECS_DTO_Base };`, ""] : []),
            `export const ECS_DTO_REGISTRY: Record<string, new () => ${baseClassName}> = Object.create(null);`,
            "",
            `export function create_ecs_dto(_name: string): ${baseClassName} | null {`,
            "    return null;",
            "}",
            "",
            '(function (root: any) {',
            '    root.pTS = root.pTS || {};',
            '    const schema = (root.pTS.__ecs_schema__ = root.pTS.__ecs_schema__ || {',
            '        components: Object.create(null),',
            '        worlds: Object.create(null),',
            '        dtos: Object.create(null),',
            '        dto_base: null,',
            '    });',
            '    schema.dtos = Object.create(null);',
            `    schema.dto_base = ${baseClassName};`,
            '})(typeof globalThis !== "undefined" ? globalThis : (typeof window !== "undefined" ? window : (typeof self !== "undefined" ? self : {})));',
            "",
        ];
        return stubLines.join("\n");
    }

    const ordered = topoSortComponents(components);
    const byName = new Map<string, IComponentDef>();
    for (const c of components) byName.set(c.name, c);

    // Track ES imports grouped by module specifier
    const importsByMod = new Map<string, Set<string>>();
    const addImport = (mod: string, sym: string) => {
        let set = importsByMod.get(mod);
        if (!set) {
            set = new Set<string>();
            importsByMod.set(mod, set);
        }
        set.add(sym);
    };
    addImport("cc", "_decorator");

    // Pre-build class bodies so we collect exact minimal imports first
    const classBlocks: string[] = [];

    for (const comp of ordered) {
        const className = buildDtoClassName(comp.name, settings);
        const parents = (comp.extends || []).map((e) => (e || "").trim()).filter((e) => byName.has(e));
        const primaryParent = parents.length > 0 ? parents[0] : null;
        const superClassName = primaryParent ? buildDtoClassName(primaryParent, settings) : baseClassName;

        // Collect own props + flattened extra parents (when multiple extends exist)
        const inheritedFromPrimary = new Set<string>();
        if (primaryParent) {
            const tmp: IPropDef[] = [];
            collectPropsRecursive(primaryParent, byName, new Set<string>(), tmp, inheritedFromPrimary);
        }
        const ownPropNames = new Set(comp.props.map((p) => p.name));
        const extraParentProps: IPropDef[] = [];
        const extraTaken = new Set<string>([...inheritedFromPrimary, ...ownPropNames]);
        for (let pi = 1; pi < parents.length; pi++) {
            collectPropsRecursive(parents[pi], byName, new Set<string>(), extraParentProps, extraTaken);
        }

        const propsToEmit: IPropDef[] = [...extraParentProps, ...comp.props];
        const propLines: string[] = [];
        const plainEntries: string[] = [];

        for (const prop of propsToEmit) {
            const isListLike = prop.complex === "array" || prop.complex === "set";
            const isMap = prop.complex === "map";
            const rawDef = (prop.defaultValue ?? "").trim();

            let decArg = "";
            let tsFieldType = "any";
            let initExpr = "null";
            let toPlainExpr = `this.${prop.name}`;

            if (isMap) {
                decArg = "";
                tsFieldType = "Record<string, any>";
                initExpr = "{}";
                toPlainExpr = `new Map(Object.entries(this.${prop.name} || {}))`;
            } else if (prop.kind === "component") {
                const targetDto = buildDtoClassName(prop.type, settings);
                if (isListLike) {
                    decArg = `{ type: [${targetDto}] }`;
                    tsFieldType = `${targetDto}[]`;
                    initExpr = "[]";
                    toPlainExpr = prop.complex === "set"
                        ? `new Set((this.${prop.name} || []).map((it) => (it ? it.to_plain() : {})))`
                        : `(this.${prop.name} || []).map((it) => (it ? it.to_plain() : {}))`;
                } else {
                    decArg = `{ type: ${targetDto} }`;
                    tsFieldType = targetDto;
                    initExpr = `new ${targetDto}()`;
                    toPlainExpr = `this.${prop.name} ? this.${prop.name}.to_plain() : new ${targetDto}().to_plain()`;
                }
            } else if (prop.kind === "enum") {
                const imp = parseTsImport(prop.tsType, prop.type);
                const defNum = rawDef === "" ? 0 : Number(rawDef);
                const defLit = rawDef === "" ? "0" : (Number.isFinite(defNum) ? String(defNum) : JSON.stringify(rawDef));
                if (imp) {
                    addImport("cc", "Enum");
                    addImport(imp.mod, imp.rootSym);
                    if (isListLike) {
                        decArg = `{ type: [Enum(${imp.expr})] }`;
                        tsFieldType = `${imp.expr}[]`;
                        initExpr = "[]";
                        toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                    } else {
                        decArg = `{ type: Enum(${imp.expr}) }`;
                        tsFieldType = imp.expr;
                        initExpr = `${defLit} as ${imp.expr}`;
                        toPlainExpr = `this.${prop.name}`;
                    }
                } else {
                    addImport("cc", "CCInteger");
                    if (isListLike) {
                        decArg = "{ type: [CCInteger] }";
                        tsFieldType = "number[]";
                        initExpr = "[]";
                        toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                    } else {
                        decArg = "{ type: CCInteger }";
                        tsFieldType = "number";
                        initExpr = defLit;
                        toPlainExpr = `this.${prop.name}`;
                    }
                }
            } else if (prop.kind === "cocos") {
                const imp = parseTsImport(prop.tsType, prop.type);
                if (imp) {
                    addImport(imp.mod, imp.rootSym);
                    if (isListLike) {
                        decArg = `{ type: [${imp.expr}] }`;
                        tsFieldType = `${imp.expr}[]`;
                        initExpr = "[]";
                        toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                    } else {
                        decArg = `{ type: ${imp.expr} }`;
                        tsFieldType = `${imp.expr} | null`;
                        initExpr = "null";
                        toPlainExpr = `this.${prop.name}`;
                    }
                } else {
                    decArg = "";
                    tsFieldType = isListLike ? "any[]" : "any";
                    initExpr = isListLike ? "[]" : "null";
                    toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : (isListLike ? `[...this.${prop.name}]` : `this.${prop.name}`);
                }
            } else {
                // Primitive types
                switch (prop.type) {
                    case "float": {
                        addImport("cc", "CCFloat");
                        const n = rawDef === "" ? 0 : Number(rawDef);
                        const lit = Number.isFinite(n) ? String(n) : "0";
                        if (isListLike) {
                            decArg = "{ type: [CCFloat] }";
                            tsFieldType = "number[]";
                            initExpr = "[]";
                            toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                        } else {
                            decArg = "{ type: CCFloat }";
                            tsFieldType = "number";
                            initExpr = lit;
                            toPlainExpr = `this.${prop.name}`;
                        }
                        break;
                    }
                    case "int": {
                        addImport("cc", "CCInteger");
                        const n = rawDef === "" ? 0 : Math.trunc(Number(rawDef));
                        const lit = Number.isFinite(n) ? String(n) : "0";
                        if (isListLike) {
                            decArg = "{ type: [CCInteger] }";
                            tsFieldType = "number[]";
                            initExpr = "[]";
                            toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                        } else {
                            decArg = "{ type: CCInteger }";
                            tsFieldType = "number";
                            initExpr = lit;
                            toPlainExpr = `this.${prop.name}`;
                        }
                        break;
                    }
                    case "string": {
                        addImport("cc", "CCString");
                        if (isListLike) {
                            decArg = "{ type: [CCString] }";
                            tsFieldType = "string[]";
                            initExpr = "[]";
                            toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                        } else {
                            decArg = "{ type: CCString }";
                            tsFieldType = "string";
                            initExpr = JSON.stringify(rawDef);
                            toPlainExpr = `this.${prop.name}`;
                        }
                        break;
                    }
                    case "boolean": {
                        addImport("cc", "CCBoolean");
                        const bLit = rawDef.toLowerCase() === "true" || rawDef === "1" ? "true" : "false";
                        if (isListLike) {
                            decArg = "{ type: [CCBoolean] }";
                            tsFieldType = "boolean[]";
                            initExpr = "[]";
                            toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                        } else {
                            decArg = "{ type: CCBoolean }";
                            tsFieldType = "boolean";
                            initExpr = bLit;
                            toPlainExpr = `this.${prop.name}`;
                        }
                        break;
                    }
                    case "Int32Array":
                    case "Uint32Array": {
                        addImport("cc", "CCInteger");
                        if (isListLike) {
                            decArg = "";
                            tsFieldType = `${prop.type}[]`;
                            initExpr = "[]";
                            toPlainExpr = prop.complex === "set" ? `new Set(this.${prop.name})` : `[...this.${prop.name}]`;
                        } else {
                            decArg = "{ type: [CCInteger] }";
                            tsFieldType = "number[]";
                            initExpr = "[]";
                            toPlainExpr = `new ${prop.type}(this.${prop.name} || [])`;
                        }
                        break;
                    }
                    case "object":
                    default: {
                        decArg = "";
                        tsFieldType = isListLike ? "Record<string, any>[]" : "Record<string, any>";
                        initExpr = isListLike ? "[]" : "{}";
                        toPlainExpr = prop.complex === "set"
                            ? `new Set(this.${prop.name})`
                            : (isListLike ? `[...this.${prop.name}]` : `Object.assign({}, this.${prop.name})`);
                        break;
                    }
                }
            }

            propLines.push(`    @property(${decArg})`);
            propLines.push(`    ${prop.name}: ${tsFieldType} = ${initExpr};`);
            plainEntries.push(`            ${prop.name}: ${toPlainExpr},`);
        }

        const block: string[] = [
            `@ccclass(${JSON.stringify(className)})`,
            `export class ${className} extends ${superClassName} {`,
            `    public override readonly __comp_name__: string = ${JSON.stringify(comp.name)};`,
            ...propLines,
            "",
            `    public override to_plain(): pTS.ecs_types.I${comp.name} {`,
            "        return {",
            ...(primaryParent ? ["            ...super.to_plain(),"] : []),
            ...plainEntries,
            `        } as pTS.ecs_types.I${comp.name};`,
            "    }",
            "}",
            "",
        ];
        classBlocks.push(block.join("\n"));
    }

    // Build final file
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
    ];

    // Emit "cc" import first, then project imports sorted deterministically
    const ccSyms = Array.from(importsByMod.get("cc") || []).sort();
    lines.push(`import { ${ccSyms.join(", ")} } from "cc";`);
    const otherMods = Array.from(importsByMod.keys()).filter((m) => m !== "cc").sort();
    for (const mod of otherMods) {
        const syms = Array.from(importsByMod.get(mod) || []).sort();
        lines.push(`import { ${syms.join(", ")} } from ${JSON.stringify(mod)};`);
    }

    lines.push("");
    lines.push("const { ccclass, property } = _decorator;");
    lines.push("");
    lines.push(`@ccclass(${JSON.stringify(baseClassName)})`);
    lines.push(`export class ${baseClassName} {`);
    lines.push('    public readonly __comp_name__: string = "";');
    lines.push("    public to_plain(): Record<string, any> {");
    lines.push("        return {};");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    if (baseClassName !== "ECS_DTO_Base") {
        lines.push(`export { ${baseClassName} as ECS_DTO_Base };`);
        lines.push("");
    }

    for (const blk of classBlocks) {
        lines.push(blk);
    }

    lines.push("export const ECS_DTO_REGISTRY = {");
    for (const comp of ordered) {
        const className = buildDtoClassName(comp.name, settings);
        lines.push(`    ${JSON.stringify(comp.name)}: ${className},`);
    }
    lines.push("} as const;");
    lines.push("");
    lines.push(`export function create_ecs_dto(name: string): ${baseClassName} | null {`);
    lines.push("    const Ctor = (ECS_DTO_REGISTRY as Record<string, new () => any>)[name];");
    lines.push("    return Ctor ? new Ctor() : null;");
    lines.push("}");
    lines.push("");
    lines.push("// Register generated @ccclass DTOs onto globalThis.pTS.__ecs_schema__.dtos for ecs.get_ccclass_comp()");
    lines.push("(function (root: any) {");
    lines.push("    root.pTS = root.pTS || {};");
    lines.push("    const schema = (root.pTS.__ecs_schema__ = root.pTS.__ecs_schema__ || {");
    lines.push("        components: Object.create(null),");
    lines.push("        worlds: Object.create(null),");
    lines.push("        dtos: Object.create(null),");
    lines.push("        dto_base: null,");
    lines.push("    });");
    lines.push(`    schema.dto_base = ${baseClassName};`);
    lines.push("    const D = (schema.dtos = Object.create(null));");
    for (const comp of ordered) {
        const className = buildDtoClassName(comp.name, settings);
        lines.push(`    D[${JSON.stringify(comp.name)}] = ${className};`);
    }
    lines.push('})(typeof globalThis !== "undefined" ? globalThis : (typeof window !== "undefined" ? window : (typeof self !== "undefined" ? self : {})));');
    lines.push("");

    return lines.join("\n");
}

export function generateDtoDts(components: IComponentDef[], rawSettings?: Partial<IEcsSettings> | null): string {
    const settings = normalizeEcsSettings(rawSettings);
    const lines: string[] = [
        "// Auto-generated by pts-ecs. Do not edit manually.",
        "declare namespace pTS {",
        "    export namespace ecs_types {",
        "        export interface IComponentDtoMeta {",
        '            base: typeof import("../scripts/ecs.dto").ECS_DTO_Base;',
        "        }",
        "",
        "        export interface IComponentDtoMap {",
    ];

    if (settings.auto_generate_dto) {
        for (const comp of components) {
            const className = buildDtoClassName(comp.name, settings);
            lines.push(`            ${comp.name}: typeof import("../scripts/ecs.dto").${className};`);
        }
    }

    lines.push("        }");
    lines.push("    }");
    lines.push("}");
    lines.push("");
    return lines.join("\n");
}
